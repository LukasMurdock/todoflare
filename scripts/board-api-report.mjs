// Public API report for @todoflare/board: every export of the package entry,
// with its signature or declaration, in packages/board/api-report.md.
//
// Usage: node scripts/board-api-report.mjs [--update]
//
// Without --update it fails if the report is out of date, so a change to the
// public API is a reviewed change to this file (wired into pnpm verify).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "packages/board/src/index.ts");
const reportPath = path.join(root, "packages/board/api-report.md");
const update = process.argv.includes("--update");

const config = ts.getParsedCommandLineOfConfigFile(path.join(root, "tsconfig.json"), {}, { ...ts.sys, onUnRecoverableConfigFileDiagnostic() {} });
const program = ts.createProgram([entry], { ...config.options, noEmit: true });
const checker = program.getTypeChecker();
const source = program.getSourceFile(entry);
const printer = ts.createPrinter({ removeComments: true });
const flags = ts.TypeFormatFlags.NoTruncation;
// Types print relative to their declaring file, so the report names types instead of machine paths.
const typeText = (type, at) => checker.typeToString(type, at, flags);

function describe(symbol) {
	const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
	const declaration = target.declarations?.[0];
	if (!declaration) return `// ${symbol.name}: no declaration`;
	const file = declaration.getSourceFile();
	if (ts.isFunctionDeclaration(declaration)) {
		const signature = checker.getSignatureFromDeclaration(declaration);
		const params = declaration.parameters.map((parameter) => {
			const name = ts.isIdentifier(parameter.name) ? parameter.name.text : "props";
			const optional = parameter.questionToken || parameter.initializer ? "?" : "";
			return `${name}${optional}: ${typeText(checker.getTypeAtLocation(parameter), declaration)}`;
		});
		return `function ${symbol.name}(${params.join(", ")}): ${typeText(signature.getReturnType(), declaration)};`;
	}
	if (ts.isInterfaceDeclaration(declaration) || ts.isTypeAliasDeclaration(declaration)) {
		const text = printer.printNode(ts.EmitHint.Unspecified, declaration, file);
		return text.replace(/^export\s+/, "").replace(new RegExp(`\\b${target.name}\\b`), symbol.name);
	}
	const type = checker.getTypeOfSymbolAtLocation(target, declaration);
	return `const ${symbol.name}: ${typeText(type, declaration)};`;
}

const moduleSymbol = checker.getSymbolAtLocation(source);
const exports = checker.getExportsOfModule(moduleSymbol).sort((a, b) => a.name.localeCompare(b.name));
const report = [
	"# @todoflare/board public API",
	"",
	"Generated by `node scripts/board-api-report.mjs --update` from `src/index.ts`.",
	"Do not edit by hand; `pnpm verify` fails when this differs from the code.",
	"",
	"```ts",
	...exports.map(describe).flatMap((text) => [text, ""]),
	"```",
	"",
].join("\n");

if (update) {
	writeFileSync(reportPath, report);
	console.log(`Wrote ${path.relative(root, reportPath)} (${exports.length} exports).`);
} else if (!existsSync(reportPath) || readFileSync(reportPath, "utf8") !== report) {
	console.error("packages/board/api-report.md is out of date: the public API changed.");
	console.error("Review the change, then run: node scripts/board-api-report.mjs --update");
	process.exit(1);
} else {
	console.log(`Board public API matches the report (${exports.length} exports).`);
}
